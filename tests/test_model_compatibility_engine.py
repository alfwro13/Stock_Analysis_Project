XGBOOST_OLD_MODEL_WARNING = (
    "[10:44:55] WARNING: /__w/xgboost/xgboost/src/collective/../data/../common/error_msg.h:83: "
    "If you are loading a serialized model (like pickle in Python, RDS in R) or\n"
    "configuration generated by an older version of XGBoost, please export the model by calling\n"
    "`Booster.save_model` from that version first, then load it back in current version."
)


def _load_emitting(message, result="model"):
    def fake_load(_path):
        warnings.warn(message, UserWarning)
        return result

    return patch("model_compatibility_engine.joblib.load", side_effect=fake_load)


def test_sidecar_mismatch_rejects_before_unpickling(tmp_path):
    artifact_path = tmp_path / "model.joblib"
    compatibility._version_path(artifact_path).write_text("0.0.0")
    reports = []
    compatibility.set_retraining_callback(
        lambda job_id, path, version: reports.append((job_id, path, version))
    )

    with patch("model_compatibility_engine.joblib.load") as load:
        with pytest.raises(compatibility.ModelVersionMismatch):
            compatibility.load_sklearn_artifact(artifact_path, "ml_training_job")

    load.assert_not_called()
    assert reports == [("ml_training_job", artifact_path, "scikit-learn 0.0.0")]


def test_dump_writes_current_version_sidecar(tmp_path):
    artifact_path = tmp_path / "model.joblib"

    compatibility.dump_sklearn_artifact({"model": "test"}, artifact_path)

    assert compatibility._version_path(artifact_path).read_text() == compatibility.sklearn_version


def test_dump_records_xgboost_version_only_for_artifacts_embedding_xgboost(tmp_path):
    from xgboost import XGBClassifier

    model_path = tmp_path / "model.joblib"
    plain_path = tmp_path / "plain.joblib"

    compatibility.dump_sklearn_artifact(XGBClassifier(n_estimators=1), model_path)
    compatibility.dump_sklearn_artifact({"model": "test"}, plain_path)

    assert compatibility._xgboost_version_path(model_path).read_text() == compatibility.xgboost_version
    assert not compatibility._xgboost_version_path(plain_path).exists()


