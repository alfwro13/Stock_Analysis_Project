def test_legacy_artifact_with_xgboost_old_model_warning_is_rejected(tmp_path):
    artifact_path = tmp_path / "model.joblib"
    reports = []
    compatibility.set_retraining_callback(
        lambda job_id, path, version: reports.append((job_id, path, version))
    )

    with _load_emitting(XGBOOST_OLD_MODEL_WARNING):
        with pytest.raises(compatibility.ModelVersionMismatch):
            compatibility.load_sklearn_artifact(artifact_path, "ml_training_job")

    assert reports == [("ml_training_job", artifact_path, "an earlier XGBoost release")]
    assert not compatibility._version_path(artifact_path).exists()


def test_xgboost_old_model_warning_is_not_leaked_to_the_log(tmp_path):
    with warnings.catch_warnings(record=True) as seen:
        warnings.simplefilter("always")
        with _load_emitting(XGBOOST_OLD_MODEL_WARNING):
            with pytest.raises(compatibility.ModelVersionMismatch):
                compatibility.load_sklearn_artifact(tmp_path / "model.joblib", "ml_training_job")

    assert seen == []


def test_unrelated_warning_during_load_is_re_emitted(tmp_path):
    with warnings.catch_warnings(record=True) as seen:
        warnings.simplefilter("always")
        with _load_emitting("something else"):
            artifact = compatibility.load_sklearn_artifact(tmp_path / "model.joblib", "ml_training_job")

    assert artifact == "model"
    assert [str(w.message) for w in seen] == ["something else"]
